// lib/typography.ts
//
// Единая типографическая шкала сайта. Все текстовые роли собраны здесь,
// компоненты не задают размеры самостоятельно.
//
// Правила:
//   1. Размер шрифта берётся только отсюда. Произвольные значения
//      (text-[11px], text-[10px]) и точечные lg:/xl:-откаты запрещены:
//      если блок не помещается — правим сетку и отступы, а не кегль.
//   2. Цвет здесь не задаётся: он зависит от подложки (светлая, тёмная,
//      инвертированная) и остаётся на стороне компонента.
//   3. Строки должны оставаться литералами — Tailwind сканирует исходники
//      статически и не увидит класс, собранный в рантайме.
//
// h1 и h2 намеренно одного размера: заголовок секции на главной и заголовок
// одноимённой страницы («Клинические случаи», «Отзывы») показывают один и
// тот же текст из админки, и разный кегль читался как рассинхрон. Разделение
// уровней держится на h3 и h4.
//
// Шкала (в пикселях):
//
//   роль       | mobile | sm 640 | md 768 | xl 1280
//   -----------|--------|--------|--------|--------
//   display    |   24   |   36   |   48   |   60
//   h1         |   24   |   30   |   36   |   36
//   h2         |   24   |   30   |   36   |   36
//   h3         |   20   |   24   |   24   |   24
//   h4         |   16   |   18   |   18   |   18
//   bodyLg     |   16   |   16   |   18   |   18
//   body       |   14   |   16   |   16   |   16
//   bodySm     |   14   |   14   |   14   |   14
//   caption    |   12   |   14   |   14   |   14
//   eyebrow    |   12   |   14   |   14   |   14
//   eyebrowSm  |   12   |   12   |   12   |   12

export const typography = {
  /** Заголовок первого экрана главной. Единственное место, где кегль
   *  поднимается выше h1 — чтобы hero не конкурировал с внутренними
   *  страницами и не уменьшался обратно на ноутбуках. */
  display:
    "break-words text-2xl font-semibold leading-[1.2] sm:text-4xl sm:leading-[1.06] md:text-5xl xl:text-6xl",

  /** Заголовок страницы. Один на страницу. */
  h1: "break-words text-2xl font-semibold leading-snug sm:text-3xl sm:leading-tight md:text-4xl",

  /** Заголовок секции. Совпадает с h1 по размеру. */
  h2: "break-words text-2xl font-semibold leading-snug sm:text-3xl sm:leading-tight md:text-4xl",

  /** Заголовок крупной карточки внутри секции: «О направлении»,
   *  «Клинический фокус», «Визуальная динамика», главная карточка
   *  направления, карточка ведущего врача. */
  h3: "text-xl font-semibold leading-snug sm:text-2xl sm:leading-tight",

  /** Заголовок карточки в сетке: направления, «Почему Lucenta»,
   *  «Когда обращаться», карточки врачей и кейсов. */
  h4: "text-base font-semibold leading-snug sm:text-lg",

  /** Надзаголовок над h1/h2. Один tracking на весь сайт. */
  eyebrow: "text-xs uppercase tracking-[0.18em] sm:text-sm",

  /** Тот же надзаголовок для узких контейнеров: боковая карточка врача
   *  на странице кейса — 300px, и 14px с разрядкой там переполняют строку.
   *  Кегль не растёт, разрядка та же — набор остаётся однородным. */
  eyebrowSm: "text-xs uppercase tracking-[0.18em]",

  /** Лид под заголовком страницы или секции. */
  bodyLg: "text-base leading-7 md:text-lg md:leading-8",

  /** Основной текст: абзацы страниц, описания в крупных карточках. */
  body: "text-sm leading-6 sm:text-base sm:leading-7",

  /** Описание в карточке сетки. Не растёт до 16px: в плитках «четыре в
   *  ряд» это добавляет по строке-две и ломает высоту ряда. Нижняя
   *  граница читаемого текста — 14px, ниже опускаться нельзя. */
  bodySm: "text-sm leading-6",

  /** Подписи, мета, служебные строки: должность, дата, лейбл показателя. */
  caption: "text-xs leading-5 sm:text-sm sm:leading-6",

  /** Цитата врача внутри карточки или текстовой колонки. */
  quote: "font-serif text-base italic leading-7 sm:text-lg sm:leading-8",

  /** Крупная цитата в hero-блоках: главная, страница команды. */
  quoteLg: "font-serif text-lg italic leading-8 sm:text-xl",

  /** Декоративная кавычка над цитатой. */
  quoteMark: "block font-serif text-5xl leading-none",
} as const;

export type TypographyRole = keyof typeof typography;